  const rect = (gx, x0, y0, x1, y1, u0, v0, u1, v1) => quad(gx, [[x0, y0], [x1, y0], [x1, y1], [x0, y1]], u0, v0, u1, v1);
  function band(gx, x0, y0, x1, y1, hw) {
    const dx = x1 - x0, dy = y1 - y0, L = Math.hypot(dx, dy);
    if (L < 0.01) return;
    const nx = -dy / L * hw, ny = dx / L * hw;
    quad(gx, [[x0 - nx, y0 - ny], [x1 - nx, y1 - ny], [x1 + nx, y1 + ny], [x0 + nx, y0 + ny]], 0, 0, 1, 1);
  }
  function setupArrays(gx, m) { for (const v of m.vfmt) { gx.SetVtxAttrFmt(0, v.attr, v.cnt, v.type, v.frac); if (m.varray[v.attr] !== undefined) gx.SetArray(v.attr, m.data, m.varray[v.attr], m.vstride[v.attr]); } }

