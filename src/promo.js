  function drawStreaks(P, gx, t) {
    const S = P.col, sf = ramp(A.streak_fade, t), ef = ramp(A.edge_fade, t);
    if (sf <= 0 && ef <= 0) return false;
    gx.SetZMode(0, 7, 0); blendAdd(gx);
    quadDesc(gx, mul(P.base, P.el[EL_LOGO]));
    const sc = (c, k) => rgb(c[0] * k, c[1] * k, c[2] * k, 1);
    for (const k of A.tracks) {
      const env = [[k.t0 - 2.5, 0], [k.t0, 1], [k.t1, 1], [k.t1 + 2.0, 0]];
      const life = ramp(env, t) * sf, g = k.v * t + k.c;
      if (life <= 0) continue;
      const [dx, dy] = lineDir(k.kind), [ax, ay] = linePoint(k.kind, k.off, -2000), [bx, by] = linePoint(k.kind, k.off, 2000);
      tevModulate(gx, P.texLine, sc(S.col_line, A.LINE_BASE * life));
      band(gx, ax, ay, bx, by, 2.0 * 0.6 / 0.8);
      const [gx0, gy0] = linePoint(k.kind, k.off, g);
      tevModulate(gx, P.texTrail, sc(S.col_trail, life));
      band(gx, gx0 - dx * 600, gy0 - dy * 600, gx0 + dx * 600, gy0 + dy * 600, 2.0 * A.TRAIL_HW / 0.8);
      if (t >= k.t0 - 0.5 && t <= k.t1 + 0.5) {
        const ca = 2.5 * A.glint[0], cb = 2.5 * A.glint[1], ha = 2.5 * A.glint[2], hb = 2.5 * A.glint[3], hk = A.glint[4];
        tevModulate(gx, P.texGauss, sc(S.col_core, life));
        band(gx, gx0 - dx * ca, gy0 - dy * ca, gx0 + dx * ca, gy0 + dy * ca, cb);
        tevModulate(gx, P.texGauss, sc(S.col_halo, hk * life));
        band(gx, gx0 - dx * ha, gy0 - dy * ha, gx0 + dx * ha, gy0 + dy * ha, hb);
      }
    }
    if (ef > 0) {
      tevModulate(gx, P.texLine, sc(S.col_edge, ef));
      for (const e of A.edges) {
        const k = A.tracks[e.track], g = k.v * t + k.c;
        let a, b;
        if (k.v > 0) { a = e.p0; b = g < e.p1 ? g : e.p1; } else { a = g > e.p0 ? g : e.p0; b = e.p1; }
        if (b <= a) continue;
        const [ax, ay] = linePoint(k.kind, k.off, a), [bx, by] = linePoint(k.kind, k.off, b);
        band(gx, ax, ay, bx, by, 2.0 * A.EDGE_HW / 0.8);
      }
    }
    return true;
  }

  /* ---------------- pixel passes ---------------- */
  const VF_NONE = [0, 0, 21, 22, 21, 0, 0];
  /* bilinear sample of an RGB float image (clamped edges) at texel position (x, y) */
  function bilin(src, w, h, x, y, out) {
    const x0 = Math.floor(x), y0 = Math.floor(y), fx = x - x0, fy = y - y0;
    const xa = x0 < 0 ? 0 : x0 > w - 1 ? w - 1 : x0, xb = x0 + 1 < 0 ? 0 : x0 + 1 > w - 1 ? w - 1 : x0 + 1;
    const ya = y0 < 0 ? 0 : y0 > h - 1 ? h - 1 : y0, yb = y0 + 1 < 0 ? 0 : y0 + 1 > h - 1 ? h - 1 : y0 + 1;
    const p00 = (ya * w + xa) * 3, p01 = (ya * w + xb) * 3, p10 = (yb * w + xa) * 3, p11 = (yb * w + xb) * 3;
    for (let c = 0; c < 3; c++) out[c] = src[p00 + c] * (1 - fx) * (1 - fy) + src[p01 + c] * fx * (1 - fy) + src[p10 + c] * (1 - fx) * fy + src[p11 + c] * fx * fy;
  }
  const WK = [0.0236, 0.0602, 0.1240, 0.1955, 0.2334, 0.1955, 0.1240, 0.0602, 0.0236];
  /* blur_pass: 9 taps drawn additively into a w x h target, each sampling src (sw x sh) over the whole target */
  function blur(src, sw, sh, w, h, horiz, step, threshold) {
    const out = new Float32Array(w * h * 3), s = [0, 0, 0], thr = c8(A.BLOOM_THR), kw = WK.map(v => c8(v) / 255);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 3; let r = 0, g = 0, b = 0;
      for (let k = 0; k < 9; k++) {
        const off = (k - 4) * step, u = (x + 0.5 - (horiz ? off : 0)) / w, v = (y + 0.5 - (horiz ? 0 : off)) / h;
        bilin(src, sw, sh, u * sw - 0.5, v * sh - 0.5, s);
        if (threshold) { for (let c = 0; c < 3; c++) s[c] = clampf((s[c] - thr) * 2, 0, 255); }
        r += s[0] * kw[k]; g += s[1] * kw[k]; b += s[2] * kw[k];
      }
      out[o] = Math.round(clampf(r, 0, 255)); out[o + 1] = Math.round(clampf(g, 0, 255)); out[o + 2] = Math.round(clampf(b, 0, 255));
    }
    return out;
  }
  function mip(src, w, h) {
    const w2 = w >> 1, h2 = h >> 1, out = new Float32Array(w2 * h2 * 3);
    for (let y = 0; y < h2; y++) for (let x = 0; x < w2; x++) for (let c = 0; c < 3; c++) {
      const a = ((2 * y) * w + 2 * x) * 3 + c, b = ((2 * y + 1) * w + 2 * x) * 3 + c;
      out[(y * w2 + x) * 3 + c] = Math.round((src[a] + src[a + 3] + src[b] + src[b + 3]) / 4);
    }
    return out;
  }

  /* ---------------- frame (promo_draw) ---------------- */
  function render(P, n, wide, gxIn) {
    const t = tOf(n), f = Math.floor(t), slam = f >= A.SLAM_FIRST && f <= A.SLAM_LAST;
    const glow = ramp(A.glow, t), fade = ramp(A.fade, t), S = P.col;
    const gx = gxIn || G.gx.create(W, H);
    let l = -296, r = 292; const tp = 224, bt = -224, nn = 50, ff = 10000;
    if (wide) { const c = (292 + -296) * 0.5, hw = (292 - -296) * 0.5 * (4 / 3); l = c - hw; r = c + hw; }
    const begin = () => {
      gx.clear([0, 0, 0]);
      gx.SetViewport(0, 0, W + 0.5, H + 0.5, 0, 1);
      gx.LoadProjectionMtx([2 / (r - l), 0, 0, -(r + l) / (r - l), 0, 2 / (tp - bt), 0, -(tp + bt) / (tp - bt), 0, 0, -1 / (ff - nn), -ff / (ff - nn)], true);
      for (let i = 0; i < 16; i++) gx.SetTevOrder(i, 0xff, 0xff, 0xff);
      commonState(gx);
    };
    /* 1. logo layers (and, on a background, their masks) */
    const layer = [null, null], mlayer = [null, null], hasBg = S.bgMode;
    for (let look = 0; look < 2; look++) {
      if (look === 0 ? !(slam || t < A.SLAM_FIRST) : !(slam || t >= A.SLAM_FIRST)) continue;
      begin(); drawLayer(P, gx, look, t); layer[look] = gx.resolveF(VF_NONE);
      if (hasBg) { MASK = true; MASK_DIV = S.inkV; begin(); drawLayer(P, gx, look, t); mlayer[look] = gx.resolveF(VF_NONE); MASK = false; }
    }
    /* 2. composite: layer copies (full-screen quads, stretched for the slam) + streaks */
    const N = W * H, scene = new Float32Array(N * 3), mask = hasBg ? new Float32Array(N * 3) : null, s3 = [0, 0, 0];
    const addLayer = (src, w, y0, y1, dst) => {
      const k = c8(w) / 255;
      dst = dst || scene;
      for (let py = 0; py < H; py++) {
        const vy = tp - (py + 0.5), v = (vy - y0) / (y1 - y0);
        if (v < 0 || v > 1) continue;
        const sy = v * H - 0.5;
        for (let x = 0; x < W; x++) { bilin(src, W, H, x, sy, s3); const o = (py * W + x) * 3; dst[o] += s3[0] * k; dst[o + 1] += s3[1] * k; dst[o + 2] += s3[2] * k; }
      }
    };
    if (slam) {
      const ls = A.slam[f - A.SLAM_FIRST], E = P.el[EL_LOGO];
      const ay = E[5] * SCALE, anchor = (CH / 2) * SCALE - (E[7] + A.SLAM_ANCHOR * E[5]) * SCALE;
      for (const [look, dy, sy, w] of ls) {
        if (w <= 0) continue;
        addLayer(layer[look], w, anchor + (tp - anchor) * sy - dy * ay, anchor + (bt - anchor) * sy - dy * ay);
        if (hasBg) addLayer(mlayer[look], w, anchor + (tp - anchor) * sy - dy * ay, anchor + (bt - anchor) * sy - dy * ay, mask);
      }
    } else {
      addLayer(layer[t < A.SLAM_FIRST ? 0 : 1], 1, tp, bt);
      if (hasBg) addLayer(mlayer[t < A.SLAM_FIRST ? 0 : 1], 1, tp, bt, mask);
    }
    begin();
    if (drawStreaks(P, gx, t)) {
      const st = gx.resolveF(VF_NONE); for (let i = 0; i < N * 3; i++) scene[i] += st[i];
      if (hasBg) { MASK = true; MASK_DIV = S.inkV; begin(); drawStreaks(P, gx, t); const sm = gx.resolveF(VF_NONE); MASK = false; for (let i = 0; i < N * 3; i++) mask[i] += sm[i]; }
    }
    for (let i = 0; i < N * 3; i++) scene[i] = Math.round(clampf(scene[i], 0, 255));
    if (hasBg) for (let i = 0; i < N * 3; i++) mask[i] = Math.round(clampf(mask[i], 0, 255));
    /* 3. glow: thresholded and blurred at 1/2, then 1/4 resolution */
    /* (on a light background the glow is drawn as ink too: from the mask, in the light's colour) */
    const ink = hasBg && S.inkV < 1;
    let b1 = null, b2 = null;
    if (glow > 0.001) {
      const W2 = W / 2, H2 = H / 2, W4 = W / 4, H4 = H / 4;
      const t1 = blur(ink ? mask : scene, W, H, W2, H2, true, 1.5 * SCALE, true);
      b1 = blur(t1, W2, H2, W2, H2, false, 1.5 * SCALE, false);
      const q = mip(b1, W2, H2);
      const t2 = blur(q, W4, H4, W4, H4, true, 2.0 * SCALE, false);
      b2 = blur(t2, W4, H4, W4, H4, false, 2.0 * SCALE, false);
    }
    /* 4. output: scene over the background (through the mask), glow, fade */
    const bg8 = S.bg.map(v => c8(v));
    const sg = glow / (2 * (1 - A.BLOOM_THR)) / 4;
    const k1 = [0, 1, 2].map(c => c8(0.9 * sg * S.bloom_tint[c]) / 255), k2 = [0, 1, 2].map(c => c8(1.2 * sg * S.bloom_tint[c]) / 255);
    const kk1 = Math.max(...k1) / S.inkV, kk2 = Math.max(...k2) / S.inkV;
    const fa = c8(1 - fade) / 255, img = new Float32Array(N * 3), g1 = [0, 0, 0], g2 = [0, 0, 0];
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      const o = (y * W + x) * 3;
      if (b1) { bilin(b1, W / 2, H / 2, (x + 0.5) / 2 - 0.5, (y + 0.5) / 2 - 0.5, g1); bilin(b2, W / 4, H / 4, (x + 0.5) / 4 - 0.5, (y + 0.5) / 4 - 0.5, g2); }
      for (let c = 0; c < 3; c++) {
        let v = scene[o + c];
        if (hasBg) v = v + bg8[c] * (1 - mask[o + c] / 255);
        if (b1 && ink) {
          /* ink glow: toward the light's colour, by the glow's strength */
          const a = clampf((g1[c] * kk1 + g2[c] * kk2) * 4 / 255, 0, 1) * 0.5, inkc = 255 * S.bloom_tint[c];
          v = clampf(v, 0, 255) * (1 - a) + inkc * a;
        } else if (b1) { v += clampf(g1[c] * k1[c] * 4, 0, 255); v = Math.min(v, 255); v += clampf(g2[c] * k2[c] * 4, 0, 255); }
        v = clampf(v, 0, 255);
        if (fa > 0.001) v = bg8[c] * fa + v * (1 - fa);
        img[o + c] = v;
      }
    }
    /* the copy to the TV picture: the IPL's vertical filter */
    const out = new Uint8ClampedArray(N * 4);
    for (let y = 0; y < H; y++) {
      const yu = Math.max(0, y - 1), yd = Math.min(H - 1, y + 1);
      for (let x = 0; x < W; x++) {
        const p = y * W + x;
        for (let c = 0; c < 3; c++) out[p * 4 + c] = (16 * img[(yu * W + x) * 3 + c] + 32 * img[p * 3 + c] + 16 * img[(yd * W + x) * 3 + c]) / 64;
        out[p * 4 + 3] = 255;
      }
    }
    return { rgba: out, t };
  }

